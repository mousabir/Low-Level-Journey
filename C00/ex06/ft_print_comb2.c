#include <unistd.h>

void	ft_print_nu(int n)
{
	char	a;
	char	z;

	a = '0' + (n / 10);
	z = '0' + (n % 10);
	write(1, &a, 1);
	write(1, &z, 1);
}

void	ft_print_comb2(void)
{
	int	n_0;
	int	n_1;

	n_0 = 0;
	while (n_0 <= 98)
	{
		n_1 = n_0 + 1;
		while (n_1 <= 99)
		{
			ft_print_nu(n_0);
			write(1, " ", 1);
			ft_print_nu(n_1);
			if (!(n_0 == 98 && n_1 == 99))
				write(1, ", ", 2);
			n_1++;
		}
		n_0++;
	}
}
