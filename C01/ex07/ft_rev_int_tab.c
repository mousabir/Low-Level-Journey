void	ft_rev_int_tab(int *tab, int size)
{
	int	i;
	int	box;

	size--;
	i = 0;
	while (i < size)
	{
		box = *(tab + i);
		*(tab + i) = *(tab + size);
		*(tab + size) = box;
		i++;
		size--;
	}
}
